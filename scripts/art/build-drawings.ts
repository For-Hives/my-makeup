/**
 * Rebuilds `src/components/art/drawings.ts` (makeup objects, line drawings) and `src/components/art/icons.ts`
 * (interface icons) from the source files of the pack, `scripts/art/icons/<name>.svg`.
 *
 *   bun --no-env-file scripts/art/build-drawings.ts   (then `bun run check`, which formats the two files)
 *
 * Every file is parsed with the HTML rewriter (no pattern matching on markup) and must be exactly one `<path>` with
 * `fill-rule="evenodd"` and a `d`, inside a `<svg viewBox="0 0 24 24" fill="currentColor">`: nothing else survives, and
 * anything else (script, style, link, metadata, a second shape) stops the build. A unit test (art-forbidden) checks
 * that the two data files hold exactly the path of each source file.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { INTERFACE_ICON_ORIGINS, LINE_DRAWING_ORIGINS, MAKEUP_OBJECT_ORIGINS } from './icon-origins'

const ROOT = join(import.meta.dir, '../..')
const SOURCES = join(import.meta.dir, 'icons')
const MAX_BYTES = 6 * 1024
const ALLOWED = new Set(['svg', 'path'])

export async function pathOf(svg: string, name: string): Promise<string> {
	const tags: string[] = []
	let data = ''
	let root = ''
	await new HTMLRewriter()
		.on('*', {
			element(element) {
				const tag = element.tagName.toLowerCase()
				tags.push(tag)
				if (tag === 'svg') {
					root = `${element.getAttribute('viewBox')}|${element.getAttribute('fill')}`
					for (const [attribute] of element.attributes)
						if (!['xmlns', 'viewbox', 'fill'].includes(attribute.toLowerCase()))
							throw new Error(`${name}: unexpected <svg> attribute ${attribute}`)
				}
				if (tag === 'path') {
					data = element.getAttribute('d') ?? ''
					for (const [attribute] of element.attributes)
						if (!['d', 'fill-rule'].includes(attribute.toLowerCase()))
							throw new Error(`${name}: unexpected <path> attribute ${attribute}`)
					if (element.getAttribute('fill-rule') !== 'evenodd') throw new Error(`${name}: fill-rule must be evenodd`)
				}
			},
		})
		.transform(new Response(svg))
		.text()
	const stray = tags.filter(tag => !ALLOWED.has(tag))
	if (stray.length > 0) throw new Error(`${name}: forbidden element ${stray.join(', ')}`)
	if (tags.filter(tag => tag === 'path').length !== 1) throw new Error(`${name}: exactly one <path> expected`)
	if (root !== '0 0 24 24|currentColor') throw new Error(`${name}: <svg> must be viewBox 0 0 24 24, fill currentColor`)
	if (!data) throw new Error(`${name}: empty path`)
	if (Buffer.byteLength(svg) > MAX_BYTES) throw new Error(`${name}: over ${MAX_BYTES} bytes`)
	return data
}

function entry(name: string, d: string): string {
	const key = /^[a-z]+$/.test(name) ? name : `'${name}'`
	const line = `\t${key}: '${d}',`
	// Biome's rule, so the generated file is already formatted: break after the key only when the string then fits.
	return line.length > 120 && `\t\t'${d}',`.length <= 120 ? `\t${key}:\n\t\t'${d}',` : line
}

async function group(constant: string, names: readonly string[]): Promise<string> {
	const lines = [`export const ${constant} = {`]
	for (const name of names) {
		const file = join(SOURCES, `${name}.svg`)
		if (!existsSync(file)) throw new Error(`${name}: ${file} is missing`)
		lines.push(entry(name, await pathOf(readFileSync(file, 'utf8'), name)))
	}
	lines.push('} as const satisfies Record<string, string>', '')
	return lines.join('\n')
}

const DRAWINGS_HEADER = `/**
 * The drawings of the art direction: makeup objects and line drawings of ONE custom pack, drawn for this site. Each
 * is one filled path on a 24 grid with a line of 1.375 units (5.7 % of the box) and round ends, drawn in \`currentColor\`.
 * Some were generated by an image model and traced in VectorCraft, the others were drawn by us in VectorCraft: the
 * origin of every one is in scripts/art/icon-origins.ts and in docs/credits-svg.md. No icon of a third-party set.
 *
 * This file is data only. It is built by scripts/art/build-drawings.ts from scripts/art/icons/*.svg: do not edit it by hand.
 */

/** The viewBox of every drawing and every icon of the pack. */
export const DRAWING_VIEW_BOX = '0 0 24 24'
`

const ICONS_HEADER = `/**
 * The interface icons of the pack (arrows, chevrons, menu, close, search, pin, check, calendar, mail, ...): the same
 * family, weight and grid as the drawings, drawn by us in VectorCraft (scripts/art/icon-origins.ts, docs/credits-svg.md).
 * One filled path each, in \`currentColor\`. A separate file from the drawings so that a client component that draws
 * an icon ships these few paths and none of the objects.
 *
 * This file is data only. It is built by scripts/art/build-drawings.ts from scripts/art/icons/*.svg: do not edit it by hand.
 */
`

export async function build(): Promise<{ drawings: string; icons: string }> {
	const known = new Set([
		...Object.keys(MAKEUP_OBJECT_ORIGINS),
		...Object.keys(LINE_DRAWING_ORIGINS),
		...Object.keys(INTERFACE_ICON_ORIGINS),
	])
	const unlisted = readdirSync(SOURCES)
		.filter(file => file.endsWith('.svg'))
		.map(file => file.slice(0, -4))
		.filter(name => !known.has(name))
	if (unlisted.length > 0) throw new Error(`source icons with no origin in icon-origins.ts: ${unlisted.join(', ')}`)
	const drawings = [
		DRAWINGS_HEADER,
		await group('MAKEUP_OBJECTS', Object.keys(MAKEUP_OBJECT_ORIGINS)),
		await group('LINE_DRAWINGS', Object.keys(LINE_DRAWING_ORIGINS)),
		'export type MakeupObjectName = keyof typeof MAKEUP_OBJECTS',
		'export type LineDrawingName = keyof typeof LINE_DRAWINGS',
		'',
	].join('\n')
	const icons = [
		ICONS_HEADER,
		await group('ICONS', Object.keys(INTERFACE_ICON_ORIGINS)),
		'export type IconName = keyof typeof ICONS',
		'',
	].join('\n')
	return { drawings, icons }
}

if (import.meta.main) {
	const { drawings, icons } = await build()
	writeFileSync(join(ROOT, 'src/components/art/drawings.ts'), drawings)
	writeFileSync(join(ROOT, 'src/components/art/icons.ts'), icons)
}
