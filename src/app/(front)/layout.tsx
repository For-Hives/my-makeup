import type { Metadata } from 'next'
import type { ReactNode } from 'react'
import { ConnexionReussie } from '@/components/analytics/SignInSucceeded'
import { WebVitals } from '@/components/analytics/WebVitals'
import { umamiLoaderScript, umamiScriptAttributes } from '@/lib/analytics/umami'
import { versionEnv } from '@/lib/env'
import { SITE_ORIGIN } from '@/lib/frozen-urls'
import packageJson from '../../../package.json'
import './globals.css'

export const metadata: Metadata = {
	metadataBase: new URL(SITE_ORIGIN),
	title: { default: 'My-Makeup', template: '%s | My-Makeup' },
	icons: { icon: '/favicon.webp' },
}

// The measure of the audience (ticket 111): the version of the build tags every event, and the
// domains Umami counts on come from the build too. Both are frozen when the pages are built.
const MESURE = umamiLoaderScript(
	umamiScriptAttributes({
		domains: process.env.NEXT_PUBLIC_UMAMI_DOMAINS,
		version: { ...versionEnv(), packageVersion: packageJson.version },
	})
)

// The only root layout of the public pages `(site)` and of the makeup artist's space `(espace)`:
// one HTML shell, so a link from one zone to the other stays a client-side navigation.
// The admin `(payload)` has its own root layout, generated by Payload, and must never load
// the stylesheet imported here.
export default function FrontLayout({ children }: { children: ReactNode }) {
	return (
		<html lang="fr">
			<head>
				{/* Inline and first: the filter of the measure exists before the Umami script does. */}
				<script dangerouslySetInnerHTML={{ __html: MESURE }} />
			</head>
			<body className="bg-neutral-50 text-neutral-900 antialiased">
				<WebVitals />
				<ConnexionReussie />
				{children}
			</body>
		</html>
	)
}
